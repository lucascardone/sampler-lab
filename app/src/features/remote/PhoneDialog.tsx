// "Use it from the phone": turn the local-network access on/off and show the QR.
import { useEffect, useState } from "react";
import { useTranslation } from "react-i18next";
import { api, type RemoteInfo } from "../../lib/api";
import { Dialog } from "../../ui/Dialog";

interface Props {
  info: RemoteInfo | null;
  setInfo: (i: RemoteInfo | null) => void;
  onClose: () => void;
  onError: (e: unknown) => void;
}

export function PhoneDialog({ info, setInfo, onClose, onError }: Props) {
  const { t } = useTranslation();
  const [busy, setBusy] = useState(false);
  useEffect(() => {
    api.remoteStatus().then(setInfo).catch(() => {});
  }, [setInfo]);

  const start = async () => {
    setBusy(true);
    try {
      setInfo(await api.remoteStart());
    } catch (e) {
      onError(e);
    } finally {
      setBusy(false);
    }
  };
  const stop = async () => {
    await api.remoteStop().catch(onError);
    setInfo(null);
  };

  return (
    <Dialog title={t("phone.title")} onClose={onClose} closeLabel={t("exportDlg.close")}>
      {!info ? (
        <>
          <p className="dialog-lead">{t("phone.lead")}</p>
          <ul className="phone-points">
            <li>{t("phone.pointSound")}</li>
            <li>{t("phone.pointSame")}</li>
            <li>{t("phone.pointSafe")}</li>
          </ul>
          <button className="primary" data-autofocus onClick={start} disabled={busy}>
            {t("phone.start")}
          </button>
        </>
      ) : (
        <div className="phone-on">
          {/* The SVG is generated by the core from our own URL (no user content). */}
          <div className="phone-qr" aria-label={t("phone.qrLabel")} role="img" dangerouslySetInnerHTML={{ __html: info.qrSvg }} />
          <div className="phone-steps">
            <ol>
              <li>{t("phone.step1")}</li>
              <li>{t("phone.step2")}</li>
              <li>{t("phone.step3")}</li>
            </ol>
            <p className="phone-url">
              <span className="muted">{t("phone.orOpen")}</span>
              <code>{info.url}</code>
            </p>
            {!info.onNetwork && <p className="phone-warn">{t("phone.noNetwork")}</p>}
            {info.needsBuild && <p className="phone-warn">{t("phone.needsBuild")}</p>}
            <p className="muted small">{t("phone.firewall")}</p>
            <button className="danger" data-autofocus onClick={stop}>
              {t("phone.stop")}
            </button>
          </div>
        </div>
      )}
    </Dialog>
  );
}
